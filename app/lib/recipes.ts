export const RECIPE_MAP: Record<string, Recipe> = Object.fromEntries(
  RECIPES.map((recipe) => [recipe.id, recipe]),
);

export const recipe = (id: string | undefined) =>
  id ? RECIPE_MAP[id] : undefined;

// Главные продукты блюда для подписи: «говядина, свёкла, капуста»
export const keyIngredients = (r: Recipe, count = 3) =>
  r.items
    .map(([id]) => PRODUCTS[id])
    .filter((p) => p && !p.staple)
    .slice(0, count)
    .map((p, i) => (i ? p.name.toLowerCase() : p.name))
    .join(", ");
